// Hold'em Lab — desktop poker trainer.
//
// Developer flags (used for automated screenshots):
//   --frames N        quit after N frames
//   --screenshot F    save a screenshot to F just before quitting
//   --tab NAME        start on play|learn|review|stats|drills|ranges|settings
//   --welcome         show the first-run welcome tour (--welcome-page N for a later page)
//   --rankings        open the hand-rankings overlay
//   --autoplay        the hero checks/calls automatically
//   --wait-hero       after N frames, keep running until it's the hero's turn
//   --drill K         open drill K (0-4) on the Drills tab; --answer answers it
//   --size WxH        initial window size

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>

#include "raylib.h"
#include "ui/app.hpp"

#if defined(__ANDROID__)
#include <android_native_app_glue.h>
extern "C" struct android_app* GetAndroidApp(void);  // provided by raylib
#endif

extern "C" {
extern const unsigned char app_icon_png[];  // generated by cmake/embed_fonts.cmake
extern const unsigned int app_icon_png_size;
}

int main(int argc, char** argv) {
  int frames = -1, width = 1440, height = 900;
  std::string shot, tab;
  bool autoplay = false, waitHero = false, drillAnswer = false, welcome = false, rankings = false;
  int welcomePage = 0;
  int drill = -1;
  for (int i = 1; i < argc; ++i) {
    std::string a = argv[i];
    if (a == "--frames" && i + 1 < argc) frames = std::atoi(argv[++i]);
    else if (a == "--screenshot" && i + 1 < argc) shot = argv[++i];
    else if (a == "--tab" && i + 1 < argc) tab = argv[++i];
    else if (a == "--autoplay") autoplay = true;
    else if (a == "--welcome") welcome = true;
    else if (a == "--welcome-page" && i + 1 < argc) {
      welcome = true;
      welcomePage = std::atoi(argv[++i]);
    } else if (a == "--rankings")
      rankings = true;
    else if (a == "--wait-hero") waitHero = true;
    else if (a == "--drill" && i + 1 < argc) drill = std::atoi(argv[++i]);
    else if (a == "--answer") drillAnswer = true;
    else if (a == "--size" && i + 1 < argc) std::sscanf(argv[++i], "%dx%d", &width, &height);
  }

#if defined(__ANDROID__)
  SetConfigFlags(FLAG_VSYNC_HINT | FLAG_FULLSCREEN_MODE);  // not every phone supports MSAA
#else
  SetConfigFlags(FLAG_WINDOW_RESIZABLE | FLAG_MSAA_4X_HINT | FLAG_VSYNC_HINT);
#endif
  SetTraceLogLevel(LOG_WARNING);
  InitWindow(width, height, "Hold'em Lab");
  SetWindowMinSize(1000, 680);
  SetExitKey(KEY_NULL);
  SetTargetFPS(60);

#if defined(__ANDROID__)
  hl::setDataDir(std::string(GetAndroidApp()->activity->internalDataPath) + "/holdemlab");
#endif
  {
    hl::ui::App app;
    app.g.load();
    {  // window / taskbar icon, embedded in the executable
      Image icon = LoadImageFromMemory(".png", app_icon_png, static_cast<int>(app_icon_png_size));
      if (icon.data) {
        SetWindowIcon(icon);
        UnloadImage(icon);
      }
    }
    if (!tab.empty()) {
      static const char* names[] = {"play", "learn", "review", "stats", "drills", "ranges", "settings"};
      for (int i = 0; i < hl::ui::TAB_COUNT; ++i)
        if (tab == names[i]) app.tab = static_cast<hl::ui::Tab>(i);
    }
    app.welcomePage = welcomePage;
    app.showRankings = rankings;
    if (welcome) app.settings.seenWelcome = false;
    else if (frames > 0) app.settings.seenWelcome = true;  // scripted runs skip the tour unless asked
    app.ctrl.newGame();
    if (drill >= 0) {
      app.tab = hl::ui::Tab::Drills;
      app.drills().open(drill);
    }
    int n = 0;
    while (!WindowShouldClose()) {
      bool stopAutoplay = waitHero && frames > 0 && n >= frames;
      if (autoplay && !stopAutoplay && app.ctrl.st.awaitingHero) {
        hl::Legal l = app.ctrl.table->legal();
        app.ctrl.heroAct({l.toCall > 0 ? hl::Act::Call : hl::Act::Check, 0});
      }
      if (drillAnswer && n == 5) app.drills().debugAnswer(app);
      app.frame();
      ++n;
      bool done = frames > 0 && n >= frames && (!waitHero || (app.ctrl.st.awaitingHero && n >= frames + 30) || n > frames + 4000);
      if (done) {
        if (!shot.empty()) {
          Image img = LoadImageFromScreen();  // TakeScreenshot() would drop the directory part
          ExportImage(img, shot.c_str());
          UnloadImage(img);
        }
        break;
      }
    }
    app.settings.save();
    app.progress.save();
    app.ctrl.saveStats();
    app.g.unload();
  }
  CloseWindow();
  return 0;
}
